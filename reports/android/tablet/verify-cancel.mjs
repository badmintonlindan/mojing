import { _android } from 'playwright';
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const adb=(...args)=>execFileSync('.tools/android-sdk/platform-tools/adb.exe',['-s','emulator-5556',...args]).toString().trim();
const device=(await _android.devices()).find(d=>d.serial()==='emulator-5556');
const page=await(await device.webView({pkg:'cn.mojing.study'})).page();
const cancel=page.getByRole('button',{name:'取消',exact:true});
const box=await cancel.boundingBox();
const viewport=await page.evaluate(()=>({width:innerWidth,height:innerHeight,dpr:devicePixelRatio}));
assert.ok(box); const native={left:0,top:48,width:2560,height:1440};
const point={x:Math.round(native.left+(box.x+box.width/2)*native.width/viewport.width),y:Math.round(native.top+(box.y+box.height/2)*native.height/viewport.height)};
adb('shell','input','tap',String(point.x),String(point.y));
await page.locator('.card-editor').waitFor({state:'detached',timeout:5000});
const result={at:new Date().toISOString(),serial:'emulator-5556',box,viewport,native,point,closed:true,method:'ADB input tap at observed DOM button projected through native WebView bounds',interpretation:'Real user touch closes the modal; earlier CDP click after OS paste was harness focus mismatch.'};
await writeFile('reports/android/tablet/cancel-touch-verification.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
await device.close();
process.exit(0);
